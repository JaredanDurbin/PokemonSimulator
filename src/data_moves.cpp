std::map<std::string, Move> Moves::EraseMapOfMoveEntry
(
   const std::map<std::string, Move>& move_data_list,
   const std::string& entry
)
{
   std::map<std::string, Move> out = move_data_list;
   out.erase(entry);
   return out;
}

std::map<std::string, Move> Moves::EraseMapOfMoveEntries
(
   const std::map<std::string, Move>& move_data_list,
   const std::vector<std::string>& entries
)
{
   std::map<std::string, Move> out = move_data_list;
   for (const auto& entry : entries)
   {
      out = Moves::EraseMapOfMoveEntry(out, entry);
   }

   return out;
}

