Moves::Moves()
{
   for (auto& moves : Moves::MOVES) 
   {
      std::map<std::string, Move> temp_map;

      for (auto& [move_name, move] : moves) 
      {
         std::string move_id = Util::ToID(move_name);
         temp_map[move_id] = move;
         temp_map[move_id].id = move_id;
         move.id = move_id;
      }

      Moves::MOVES_BY_ID.push_back(temp_map);
   }
}

