std::map<std::string, Move> Moves::ExtendMapOfMove
(
   const std::vector<std::map<std::string, Move>>& move_list
)
{
   std::map<std::string, Move> out = move_list.at(0);
   for (int i = 1; i < move_list.size(); i++)
   {
      for (const auto& [key, value] : move_list[i])
      {
         if (out.find(key) != out.end())
         {
            Moves::UpdateMoveValues(out.at(key), value);
         }
         else
         {
            out.insert({key, value});
         }
      }
   }

   return out;
}

